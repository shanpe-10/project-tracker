const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const fields = new Map();
const context = vm.createContext({console, Date, Intl, setTimeout, clearTimeout, setInterval:()=>1, clearInterval(){}, document:{addEventListener(){}, getElementById:id=>fields.get(id)||null, querySelectorAll:()=>[]}, localStorage:{getItem:()=>null}, URLSearchParams, Map, Set, alert(){}});
context.window=context;
context.addEventListener=()=>{};
for (const name of ['state','utils','projects','timeline']) vm.runInContext(fs.readFileSync(path.join(__dirname,'../public/js/'+name+'.js'),'utf8'),context);
const dates=context.getProjectMilestoneDates;
for (const [start,expected] of Object.entries({'2026-01-31':'2026-02-28','2024-01-31':'2024-02-29','2026-12-31':'2027-01-31','2026-10-05':'2026-11-05'})) {
    const result=dates({biddingDate:start});
    for (const field of ['preInspectionDueDate','ntpDueDate','materialTestingDueDate']) assert.equal(result[field],expected);
}
assert.equal(dates({biddingDate:'2026-02-30'}).ntpDueDate,'');
assert.equal(dates({contractRef:'2026-10-01',ntpDate:'2026-10-20',contractDuration:60}).finalInspectionDueDate,'2026-11-30');
assert.equal(dates({contractRef:'2026-10-01',contractDuration:60.5}).finalInspectionDueDate,'2026-11-30');
assert.equal(dates({contractEndDate:'2026-11-01',ldNewCompletionDate:'2026-12-01'}).finalInspectionDueDate,'2026-11-01');
for (const invalid of ['60 working days','0','-1','60 days','999999999999999']) assert.equal(dates({ntpDate:'2026-10-01',contractDuration:invalid}).finalInspectionDueDate,'');
context.timelineDaySettings={ntp:7,material:15,finalInspection:7};
const project={status:'Pending',biddingDate:'2026-01-31',contractEndDate:'2026-03-20'};
const alerts=(day,extra={})=>context.getProjectMilestoneAlerts({...project,...extra},day);
const types=(day,extra)=>Array.from(alerts(day,extra),a=>a.type);
assert(!types('2026-03-12').includes('final-inspection'));
assert(types('2026-03-13').includes('final-inspection'));
assert(types('2026-03-20').includes('final-inspection'));
assert(types('2026-03-21').includes('final-inspection-overdue'));
assert(!types('2026-03-21',{timelineAlertsCompleted:['final-inspection']}).includes('final-inspection-overdue'));
assert(!types('2026-03-13',{finalInspection:'2026-03-12'}).includes('final-inspection'));
assert(types('2026-03-13',{finalInspection:'2026-03-15'}).includes('final-inspection'));
for (const extra of [{status:'Completed'},{status:'Released'},{archivedAt:'2026-01-01'},{timelineCompletedMarked:true}]) assert.equal(alerts('2026-03-13',extra).length,0);
assert.deepEqual(types('2026-02-28'),['pre-inspection','ntp-due','material-test']);
assert(alerts('2026-02-28').every(a=>a.dueDate==='2026-02-28'));
assert(types('2026-03-01').includes('pre-inspection-overdue'));
assert(types('2026-03-01',{'':'2026-02-25'}).includes('material-overdue'));
assert(!types('2026-03-01',{preInspection:'2026-02-25'}).includes('pre-inspection-overdue'));
assert(!types('2026-03-01',{ntpDate:'2026-02-25'}).includes('ntp-due-overdue'));
assert.equal(context.checkMaterialTestOverdueWindowAlert('2020-01-01','Pending',project),false);
assert.equal(context.checkMaterialTestOverdueWindowAlert('2020-01-01','Pending',{}),true);
assert.equal(context.resolvedAlertCategory('final-inspection-overdue'),'finalInspection');
assert.equal(context.projectMilestoneDueDate(project,'material-overdue'),'2026-02-28');
for (const id of ['biddingDate','ntpDate','contractRef','contractDuration','contractEndDate','ldNewCompletionDate','preInspectionDueDate','ntpDueDate','materialTestingDueDate','finalInspectionDueDate','preInspection']) fields.set(id,{value:''});
fields.get('biddingDate').value='2026-01-31';
fields.get('preInspection').value='2026-02-25';
fields.get('ntpDate').value='2026-02-20';
fields.get('contractRef').value='2026-02-20';
fields.get('contractDuration').value='30';
context.updateProjectMilestoneDates();
assert.equal(fields.get('ntpDueDate').value,'2026-02-28');
assert.equal(fields.get('preInspection').value,'2026-02-25');
assert.equal(fields.get('ntpDate').value,'2026-02-20');
assert.equal(fields.get('finalInspectionDueDate').value,'2026-03-22');
fields.get('biddingDate').value='';
context.updateProjectMilestoneDates();
assert.equal(fields.get('ntpDueDate').value,'');
console.log('Milestone deadline regressions passed: calendar months, contract duration/extensions, alert boundaries, resolution, settings and actual-date preservation.');
