-- PostgreSQL 16+ tracker schema. Run inside an existing UTF8 database.
-- ICU primary-strength collation preserves case/accent-insensitive unique keys.
CREATE COLLATION IF NOT EXISTS tracker_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);
CREATE OR REPLACE FUNCTION tracker_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME = 'projects' THEN
  IF (NEW.data - 'status') = (OLD.data - 'status')
     AND (to_jsonb(NEW) - ARRAY['data','project_status','updated_at']) = (to_jsonb(OLD) - ARRAY['data','project_status','updated_at']) THEN
   NEW.updated_at = OLD.updated_at; RETURN NEW;
  END IF;
 END IF;
 NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION tracker_date(value text) RETURNS date LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
 IF value !~ '^\d{4}-\d{2}-\d{2}$' THEN RETURN NULL; END IF;
 RETURN value::date;
EXCEPTION WHEN datetime_field_overflow OR invalid_datetime_format THEN RETURN NULL;
END $$;

CREATE TABLE IF NOT EXISTS "users" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "username" varchar(80) COLLATE tracker_ci NOT NULL,
  "full_name" varchar(160) NOT NULL,
  "password_hash" varchar(255) NOT NULL,
  "password_encrypted" text NULL,
  "role" varchar(20) NOT NULL DEFAULT 'staff' CHECK (role IN ('superadmin','admin','staff')),
  "active" boolean NOT NULL DEFAULT true,
  "can_create" boolean NOT NULL DEFAULT false,
  "can_edit" boolean NOT NULL DEFAULT false,
  "can_import" boolean NOT NULL DEFAULT false,
  "can_export" boolean NOT NULL DEFAULT false,
  "can_delete" boolean NOT NULL DEFAULT false,
  "can_delete_all" boolean NOT NULL DEFAULT false,
  "can_resolve_alerts" boolean NOT NULL DEFAULT false,
  "can_archive" boolean NOT NULL DEFAULT false,
  "can_edit_alerts" boolean NOT NULL DEFAULT false,
  "created_at" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "profile_photo" varchar(255) DEFAULT NULL,
  "profile_photo_updated_at" timestamp without time zone NULL DEFAULT NULL,
  PRIMARY KEY ("id"),
  CONSTRAINT "username" UNIQUE ("username")
);


CREATE TABLE IF NOT EXISTS "login_attempts" (
  "attempt_key" char(64) NOT NULL,
  "failed_count" integer NOT NULL DEFAULT 0 CHECK ("failed_count" >= 0),
  "first_failed_at" timestamp without time zone NOT NULL,
  "locked_until" timestamp without time zone DEFAULT NULL,
  "updated_at" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("attempt_key")
);
CREATE INDEX IF NOT EXISTS "login_attempts_updated_idx" ON "login_attempts" ("updated_at");
DROP TRIGGER IF EXISTS login_attempts_touch_updated_at ON "login_attempts";
CREATE TRIGGER login_attempts_touch_updated_at BEFORE UPDATE ON "login_attempts" FOR EACH ROW EXECUTE FUNCTION tracker_touch_updated_at();

