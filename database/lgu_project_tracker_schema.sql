-- Deletion approval requests retain their history after projects or accounts are removed.
CREATE TABLE IF NOT EXISTS deletion_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type varchar(20) NOT NULL,
    bulk boolean NOT NULL DEFAULT false,
    status varchar(20) NOT NULL DEFAULT 'pending',
    requested_by bigint NULL,
    requester json NOT NULL,
    reason text NOT NULL,
    requested_at timestamp NOT NULL,
    reviewer json NULL,
    reviewed_at timestamp NULL,
    decision_note text NULL,
    confirmation_hash varchar(64) NULL,
    deleted_by json NULL,
    deleted_at timestamp NULL
);
CREATE INDEX IF NOT EXISTS deletion_requests_requested_by_index ON deletion_requests(requested_by);
CREATE INDEX IF NOT EXISTS deletion_requests_status_id_index ON deletion_requests(status, id);
CREATE TABLE IF NOT EXISTS deletion_request_targets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES deletion_requests(id) ON DELETE CASCADE,
    target_type varchar(20) NOT NULL,
    target_id bigint NOT NULL,
    project_id bigint NULL,
    active_key varchar(80) NULL UNIQUE,
    fingerprint varchar(64) NOT NULL,
    snapshot json NOT NULL
);
CREATE INDEX IF NOT EXISTS deletion_request_targets_project_id_index ON deletion_request_targets(project_id);
CREATE INDEX IF NOT EXISTS deletion_request_targets_request_id_index ON deletion_request_targets(request_id);

-- Clearing history affects only the selected user's view and scope.
CREATE TABLE IF NOT EXISTS deletion_request_history_hidden (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    request_id bigint NOT NULL REFERENCES deletion_requests(id) ON DELETE CASCADE,
    scope varchar(10) NOT NULL,
    hidden_at timestamp NOT NULL,
    CONSTRAINT deletion_history_hidden_pk PRIMARY KEY (user_id, scope, request_id)
);

